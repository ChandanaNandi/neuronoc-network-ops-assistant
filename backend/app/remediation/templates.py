# ---------- registry + lookup ----------


TEMPLATES = {
    "bgp_neighbor_down": template_bgp_neighbor_down,
    "interface_errors_spike": template_interface_errors_spike,
    "latency_spike": template_latency_spike,
    "route_missing": template_route_missing,
    "acl_blocking_traffic": template_acl_blocking_traffic,
}

# Map correlation themes (from Phase 5) onto the closest specific template.
_THEME_FALLBACK = {
    "routing_failure": template_bgp_neighbor_down,
    "interface_physical_issue": template_interface_errors_spike,
    "latency_or_loss": template_latency_spike,
    "policy_block": template_acl_blocking_traffic,
}


def pick_template(incident_type: str | None, themes: list[str] | None):
    """Pick a template by incident_type first; fall back to correlation theme."""
    if incident_type and incident_type in TEMPLATES:
        return TEMPLATES[incident_type]
    for theme in themes or []:
        if theme in _THEME_FALLBACK:
            return _THEME_FALLBACK[theme]
    return template_default
