# ---------- Route missing ----------


def template_route_missing(
    incident_id: UUID, report: dict[str, Any], _rca: Any
) -> RemediationPlan:
    playbook = _PLAYBOOK_HEADER.format(incident_id=incident_id) + """
- name: Missing prefix investigation (DRAFT)
  hosts: receiver
  gather_facts: false
  vars:
    prefix: "REPLACE_WITH_PREFIX/MASK"
  tasks:
    - name: Pre-check - confirm prefix is absent on the receiver
      ansible.builtin.command: "show ip route {{ prefix }}"
      register: route_before
      changed_when: false

    # Sender-side prefix-list / route-map edits are an explicit follow-up
    # plan, NOT executed here.

    - name: Post-check - re-query the receiver for the prefix
      ansible.builtin.command: "show ip route {{ prefix }}"
      register: route_after
      changed_when: false
"""
    return RemediationPlan(
        incident_id=incident_id,
        plan_type="route_advertisement_recovery",
        title="Route missing - walk advertisement path and fix policy filter (draft)",
        risk="medium",
        requires_approval=True,
        summary=(
            "Draft plan to walk the BGP advertisement path for a missing prefix, "
            "identify whether the loss is at the sender's outbound policy or the "
            "receiver's inbound policy, and propose a targeted permit-entry fix. "
            "No policy edit is performed automatically."
        ),
        pre_checks=[
            "On receiver: `show ip route <prefix>` to confirm the prefix is absent.",
            "On sender: `show ip bgp <prefix>` to confirm the prefix is still in its local RIB.",
            "On sender: `show bgp neighbors <peer> advertised-routes` to confirm the prefix is being announced.",
            "On both sides: dump the active prefix-list / route-map / community policy that governs this peer.",
            "Diff the active policy against the last known-good revision in version control.",
        ],
        proposed_commands=[
            "show ip route <prefix>",
            "show ip bgp <prefix>",
            "show bgp neighbors <peer-ip> advertised-routes | include <prefix>",
            "show ip prefix-list <policy-name>",
            "# REQUIRES APPROVAL: add explicit `permit <prefix>` entry to the failing prefix-list / route-map.",
        ],
        proposed_ansible_playbook=playbook,
        post_checks=[
            "On receiver: `show ip route <prefix>` returns a valid route via the expected next hop.",
            "On sender: `show bgp neighbors <peer> advertised-routes` includes the prefix.",
            "Run a reachability test from the receiver into the prefix.",
        ],
        rollback_steps=[
            "If a prefix-list `permit` entry was added, remove the same entry by sequence number.",
            "If a route-map was modified, revert from the captured pre-change config.",
            "Restore the prior policy revision from version control if anything else changed.",
        ],
        validation_criteria=[
            "Prefix present in the receiver's RIB with a valid next hop.",
            "Reachability test into the prefix returns 0% loss for 5 consecutive minutes.",
            "No unintended additional prefixes appear in the advertised-routes diff.",
        ],
        safety_notes=[
            "DRAFT ONLY - do not run without explicit human approval.",
            "Do not apply a `permit any` to fix the symptom; add only the specific missing prefix.",
            "Bouncing the BGP session is a separate, riskier plan.",
        ],
        source=PLAN_SOURCE,
        confidence=_confidence_from(report),
    )


# ---------- ACL blocking traffic ----------


def template_acl_blocking_traffic(
    incident_id: UUID, report: dict[str, Any], _rca: Any
) -> RemediationPlan:
    playbook = _PLAYBOOK_HEADER.format(incident_id=incident_id) + """
- name: ACL / policy review (DRAFT)
  hosts: denying_device
  gather_facts: false
  vars:
    acl_name: "REPLACE_WITH_ACL_NAME"
  tasks:
    - name: Pre-check - dump current ACL
      ansible.builtin.command: "show access-list {{ acl_name }}"
      register: acl_before
      changed_when: false

    - name: Pre-check - count deny hits for the affected flow
      ansible.builtin.command: "show access-list {{ acl_name }} | include deny|hits"
      register: deny_hits
      changed_when: false

    # An explicit permit insertion is staged here but gated until approval.
    - name: Insert explicit permit ahead of the deny (REQUIRES APPROVAL)
      ansible.builtin.command: >-
        configure terminal ;
        access-list {{ acl_name }} 15 permit ip <src/mask> <dst/mask> ;
        end
      # SAFETY GUARD: flip to true ONLY after diff review + change record.
      when: false
"""
    return RemediationPlan(
        incident_id=incident_id,
        plan_type="acl_policy_review",
        title="ACL / policy review - diff change and insert targeted permit (draft)",
        risk="medium",
        requires_approval=True,
        summary=(
            "Draft plan to review the recent ACL / policy change, diff against "
            "the previous revision, confirm the denied flow is intended to be "
            "permitted, and propose inserting an explicit permit ahead of the "
            "deny. Policy is not modified automatically."
        ),
        pre_checks=[
            "Pull the change record / commit log for the most recent ACL push on the denying device.",
            "Run `show access-list <name>` and diff against the previous revision.",
            "Inspect deny-hit counters for the affected source/destination pair.",
            "Confirm with the application owner that the affected flow is intended to be permitted.",
            "Run a reachability test from the affected source to confirm the deny location is the suspected hop.",
        ],
        proposed_commands=[
            "show access-list <name>",
            "show access-list <name> | include deny|hits",
            "# REQUIRES APPROVAL: insert explicit permit ahead of the matching deny.",
            "#   access-list <name> <seq> permit ip <src/mask> <dst/mask>",
        ],
        proposed_ansible_playbook=playbook,
        post_checks=[
            "Re-run `show access-list <name>` and confirm the new permit appears at the intended sequence.",
            "Re-run the reachability test - should now succeed.",
            "Confirm deny-hit counters for the previously affected flow stop incrementing.",
        ],
        rollback_steps=[
            "Remove the inserted permit by its sequence number: `no access-list <name> <seq>`.",
            "If anything else was edited, restore the previous policy revision from version control.",
        ],
        validation_criteria=[
            "Affected source -> destination reachability test passes.",
            "Deny-hit counter for the affected flow stops climbing for at least 10 minutes.",
            "No unintended additional flows are now permitted (diff with intended change).",
        ],
        safety_notes=[
            "DRAFT ONLY - do not run without explicit human approval.",
            "Do not add a catch-all `permit ip any any` to mask the symptom.",
            "Do not disable the ACL temporarily as a workaround.",
            "All ACL edits must reference an approved change record.",
        ],
        source=PLAN_SOURCE,
        confidence=_confidence_from(report),
    )


