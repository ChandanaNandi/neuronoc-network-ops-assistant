"""Phase 7 deterministic remediation templates.

CRITICAL SAFETY CONTRACT:
- These templates produce TEXT ONLY. Nothing here executes commands, calls
  Ansible, talks to a device, or imports any remote-execution library.
- Every plan is marked `requires_approval=True`.
- Every plan ships with rollback steps + safety notes.
- For risky operations, `proposed_commands` and the Ansible draft both include
  explicit "REQUIRES APPROVED CHANGE WINDOW" markers, and the Ansible draft
  gates the risky task on `when: false` so it cannot run as-is.
"""

from __future__ import annotations

from typing import Any
from uuid import UUID

from app.schemas.remediation import RemediationPlan

PLAN_SOURCE = "phase7_template"

_PLAYBOOK_HEADER = (
    "# DRAFT ONLY - DO NOT RUN WITHOUT REVIEW AND EXPLICIT HUMAN APPROVAL\n"
    "# Generated by NeuroNOC Phase 7 remediation planner for incident {incident_id}.\n"
    "# This file is intentionally non-executable: risky tasks are gated on `when: false`.\n"
    "# Required changes before any run:\n"
    "#   1) An approved change record.\n"
    "#   2) A captured rollback plan.\n"
    "#   3) Operator flips the `when:` guard ONLY after both above are in place.\n"
)


def _confidence_from(report: dict[str, Any]) -> float:
    try:
        return float(report.get("confidence", 0.0) or 0.0)
    except (TypeError, ValueError):
        return 0.0


# ---------- BGP neighbor down ----------


def template_bgp_neighbor_down(
    incident_id: UUID, report: dict[str, Any], _rca: Any
) -> RemediationPlan:
    playbook = _PLAYBOOK_HEADER.format(incident_id=incident_id) + """
- name: BGP neighbor session investigation and soft reset (DRAFT)
  hosts: edge_router
  gather_facts: false
  vars:
    bgp_neighbor_ip: "REPLACE_WITH_NEIGHBOR_IP"
  tasks:
    - name: Pre-check - capture 'show bgp summary' BEFORE
      ansible.builtin.command: "show bgp summary"
      register: bgp_before
      changed_when: false

    - name: Pre-check - capture 'show interface' on the BGP-bearing link
      ansible.builtin.command: "show interface"
      register: iface_before
      changed_when: false

    - name: Soft inbound reset (REQUIRES APPROVED CHANGE WINDOW)
      ansible.builtin.command: "clear ip bgp {{ bgp_neighbor_ip }} soft in"
      # SAFETY GUARD: flip to true ONLY after operator approval and an open change window.
      when: false

    - name: Post-check - capture 'show bgp summary' AFTER
      ansible.builtin.command: "show bgp summary"
      register: bgp_after
      changed_when: false
"""
    return RemediationPlan(
        incident_id=incident_id,
        plan_type="bgp_neighbor_recovery",
        title="BGP neighbor recovery - investigate L1 and soft-reset session (draft)",
        risk="medium",
        requires_approval=True,
        summary=(
            "Draft plan to investigate a flapping BGP session, capture pre/post "
            "evidence, and optionally perform an inbound soft-reset under an "
            "approved change window. No automatic execution."
        ),
        pre_checks=[
            "Capture 'show bgp summary' on both peers and diff against last known-good baseline.",
            "Capture 'show interface <link>' for L1/CRC errors on the BGP-bearing link.",
            "Pull recent syslog around the state change; look for BGP NOTIFY codes.",
            "Confirm an approved change window is open before any state-changing command.",
        ],
        proposed_commands=[
            "show bgp summary",
            "show bgp neighbor <neighbor-ip>",
            "show interface <bgp-bearing-link>",
            "# REQUIRES APPROVAL: clear ip bgp <neighbor-ip> soft in",
        ],
        proposed_ansible_playbook=playbook,
        post_checks=[
            "Re-capture 'show bgp summary' and verify neighbor returns to Established.",
            "Verify advertised-prefix count returns to baseline.",
            "Run end-to-end reachability test for the affected downstream prefixes.",
        ],
        rollback_steps=[
            "A soft-reset is itself non-destructive; if the session does not recover, do nothing further automatically.",
            "If a config change was made (timers, password, prefix-list), revert it from the captured pre-change config.",
            "Escalate to network on-call if Established state is not restored within the change window.",
        ],
        validation_criteria=[
            "Neighbor state Established for at least 5 consecutive minutes.",
            "Received prefix count matches the prior baseline (+/- 5%).",
            "End-to-end reachability test from the affected downstream returns 0% loss.",
        ],
        safety_notes=[
            "DRAFT ONLY - do not run without explicit human approval.",
            "Soft inbound reset can briefly affect traffic; perform only inside the approved window.",
            "Do not perform a hard reset (`clear ip bgp <neighbor>`) as a first step.",
            "Do not reload the router.",
            "Capture and attach pre/post evidence to the incident.",
        ],
        source=PLAN_SOURCE,
        confidence=_confidence_from(report),
    )


# ---------- Interface error spike ----------


def template_interface_errors_spike(
    incident_id: UUID, report: dict[str, Any], _rca: Any
) -> RemediationPlan:
    playbook = _PLAYBOOK_HEADER.format(incident_id=incident_id) + """
- name: Interface error investigation (DRAFT - observational only)
  hosts: affected_device
  gather_facts: false
  tasks:
    - name: Capture interface counters
      ansible.builtin.command: "show interface eth1"
      register: iface_counters
      changed_when: false

    - name: Capture optics diagnostics
      ansible.builtin.command: "show interface eth1 transceiver"
      register: optics
      changed_when: false

    # NO config-change tasks in this template by design.
    # Physical inspection + optic replacement is performed out-of-band under
    # an approved change window after the diagnostics above confirm a fault.
"""
    return RemediationPlan(
        incident_id=incident_id,
        plan_type="interface_physical_investigation",
        title="Interface error spike - diagnose physical layer (draft, no config changes)",
        risk="low",
        requires_approval=True,
        summary=(
            "Draft plan for an interface error / drop spike. First action is "
            "observation, NOT a device config change. Any physical action "
            "(optic clean/reseat/replace) is performed out-of-band under an "
            "approved change window."
        ),
        pre_checks=[
            "Snapshot interface counters (errors, drops, packets) twice 60 seconds apart - delta matters more than absolute.",
            "Capture optic light levels and temperature; compare against vendor spec.",
            "Capture peer-side interface counters; one-sided errors usually point at the local optic.",
            "Confirm no recent re-cabling, optic swap, or topology change happened just before the alarm.",
        ],
        proposed_commands=[
            "show interface <iface>",
            "show interface <iface> transceiver",
            "show interface <iface> counters errors",
            "# No config changes proposed at this stage - physical inspection first.",
        ],
        proposed_ansible_playbook=playbook,
        post_checks=[
            "After physical action: re-capture counters 5 and 30 minutes later; expect error rate at or below baseline.",
            "Compare optic RX power against vendor spec; should now be inside the spec window.",
        ],
        rollback_steps=[
            "No software rollback applicable - the template proposes observation only.",
            "If an optic was physically replaced, the rollback is to re-install the previous optic.",
        ],
        validation_criteria=[
            "Error rate < 50 events/min sustained for 30 minutes.",
            "Optic RX power within vendor spec.",
            "Peer-side counters also show error rate returning to baseline.",
        ],
        safety_notes=[
            "DRAFT ONLY - do not run without explicit human approval.",
            "Do not propose 'shut / no shut' as a first action; it can mask a failing optic.",
            "Do not bring the interface administratively down without traffic-shift planning.",
            "Physical optic / fiber work is outside the scope of this software-only plan.",
        ],
        source=PLAN_SOURCE,
        confidence=_confidence_from(report),
    )


